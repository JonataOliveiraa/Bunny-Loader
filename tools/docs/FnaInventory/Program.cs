using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

string root = Path.GetFullPath(args.Length > 0 ? args[0] : ".");
string fnaDir = Path.Combine(root, "exmod_tmod/tModLoader/FNA/src");
string dumpFile = Path.Combine(root, "refs/dump.cs");
string[] ourDirs = { Path.Combine(root, "app/src/main/csharp/BunnyLoader"), Path.Combine(root, "app/build/generated/csharp") };
string exampleDir = Path.Combine(root, "exmod_tmod/tModLoader/ExampleMod");
string toolDir = Path.Combine(root, "tools/docs/FnaInventory");
string reportFile = Path.Combine(root, "docs/historico/inventario-fna.md");
string membersFile = Path.Combine(toolDir, "members.txt");

if (!Directory.Exists(fnaDir) || Directory.GetFiles(fnaDir, "*.cs").Length == 0)
{
    Console.Error.WriteLine("FNA source missing: run 'git submodule update --init FNA' in exmod_tmod/tModLoader");
    return 1;
}

if (!Directory.Exists(ourDirs[1]))
{
    Console.Error.WriteLine("generated proxies missing: build BunnyLoader.dll first (tools/tests/build-cs.sh or gradle)");
    return 1;
}

var fnaFiles = Directory.GetFiles(fnaDir, "*.cs", SearchOption.AllDirectories)
    .Where(f => !f.Replace('\\', '/').Contains("/FNAPlatform/"))
    .Select(f => (f, File.ReadAllText(f)))
    .ToList();
var fna = Scan(fnaFiles, true);

var dump = Scan(DumpSections(dumpFile), true);

var ourFiles = ourDirs
    .SelectMany(d => Directory.GetFiles(d, "*.cs", SearchOption.AllDirectories))
    .Select(f => (f, File.ReadAllText(f)))
    .Where(x => x.Item2.Contains("namespace Microsoft.Xna"))
    .ToList();
var ours = Scan(ourFiles, false);

Flatten(fna);
Flatten(dump);
Flatten(ours);

string exampleText = Directory.Exists(exampleDir)
    ? string.Join("\n", Directory.GetFiles(exampleDir, "*.cs", SearchOption.AllDirectories).Select(File.ReadAllText))
    : "";

var decisions = ReadDecisions(Path.Combine(toolDir, "decisions.txt"));
var rows = new List<Row>();
var members = new StringBuilder();

foreach (TypeInfo type in fna.Values.OrderBy(t => t.FullName, StringComparer.Ordinal))
{
    TypeInfo? our = Find(ours, type, out string ourNote);
    TypeInfo? game = Find(dump, type, out string gameNote);
    int uses = Count(exampleText, $@"\b{Regex.Escape(type.Name)}\b");
    var missing = new List<string>();
    int same = 0, overload = 0;

    foreach (Member m in type.All.Values.OrderBy(m => m.Signature, StringComparer.Ordinal))
    {
        if (our != null && Callable(our, m)) { same++; continue; }

        bool named = our != null && our.Names.Contains(m.Name);
        if (named) overload++;

        string inGame = game == null ? "no type" : Callable(game, m) ? "game has it" : game.Names.Contains(m.Name) ? "game has another overload" : "game lacks it";
        int memberUses = uses == 0 ? 0 : Count(exampleText, $@"\.{Regex.Escape(m.Name.Split('`')[0])}\b");
        missing.Add($"    {(named ? "~" : "-")} {m.Kind} {m.Signature}  [{inGame}]{(memberUses > 0 ? $" ExampleMod .{m.Name} x{memberUses}" : "")}");
    }

    int total = type.All.Count;
    var decided = Decide(decisions, type.FullName);
    string decision = our != null && same == total ? "done" : decided?.Kind ?? Suggest(type, our, game, same, total);
    string note = decided?.Note ?? "";
    rows.Add(new Row(type, our, game, ourNote, gameNote, same, overload, total, uses, decision, note));

    if (missing.Count > 0)
    {
        members.AppendLine($"{type.FullName}  ({decision}; BL {(our == null ? "no type" : $"{same}/{total}")}; game {(game == null ? "no type" : "has type")}{(type.Native ? "; native in FNA" : "")})");
        foreach (string line in missing) members.AppendLine(line);
        members.AppendLine();
    }
}

WriteReport();
File.WriteAllText(membersFile, members.ToString().Replace("\r\n", "\n"));

int fullyCovered = rows.Count(r => r.Total > 0 && r.Same == r.Total);
Console.WriteLine($"FNA public types {rows.Count}: BL has {rows.Count(r => r.Our != null)} ({fullyCovered} complete), game has {rows.Count(r => r.Game != null)}");
foreach (var g in rows.GroupBy(r => r.Decision).OrderBy(g => g.Key))
    Console.WriteLine($"  {g.Key}: {g.Count()} types, {g.Sum(r => r.Total - r.Same)} members missing");
return 0;

void WriteReport()
{
    var sb = new StringBuilder();
    sb.AppendLine("# FNA inventory");
    sb.AppendLine();
    sb.AppendLine("Generated by `tools/docs/FnaInventory` (do not edit by hand; decisions go in");
    sb.AppendLine("`tools/docs/FnaInventory/decisions.txt`). It compares the public API of FNA as");
    sb.AppendLine("tModLoader ships it (`exmod_tmod/tModLoader/FNA`, submodule) with the mobile");
    sb.AppendLine("game's own XNA (`refs/dump.cs`) and with what `BunnyLoader.dll` exposes to mods");
    sb.AppendLine("(hand-written sources plus the ProxyGen output). Missing members per type are in");
    sb.AppendLine("`tools/docs/FnaInventory/members.txt`.");
    sb.AppendLine();
    sb.AppendLine("Kinds:");
    sb.AppendLine();
    sb.AppendLine("- `done`: every public member of the FNA type exists in BL with the same signature.");
    sb.AppendLine("- `1 copy`: plain managed code in FNA (no FNA3D, FAudio, SDL or platform call);");
    sb.AppendLine("  it can be copied (Ms-PL, keep the notice) and converted where it crosses the bridge.");
    sb.AppendLine("- `2 game`: built over what the mobile game or Unity already has, as");
    sb.AppendLine("  `Texture2D.SetData` was (the tool guesses it when the game has the type).");
    sb.AppendLine("- `3 native`: FNA calls native code and the game lacks the type: new native code");
    sb.AppendLine("  (GL on the render thread, like the sprite shaders).");
    sb.AppendLine("- `out`: belongs to the engine the game already owns (window, game loop, device");
    sb.AppendLine("  setup, SDL input, FAudio), decided in `decisions.txt`.");
    sb.AppendLine("- A kind with `?` is the tool's guess; one without it was decided by hand.");
    sb.AppendLine();
    sb.AppendLine("Columns: **BL** members with the same signature / FNA members (`+n` more exist");
    sb.AppendLine("with another signature); **Game** whether the mobile dump has the type;");
    sb.AppendLine("**ExampleMod** how many times tModLoader's ExampleMod names the type.");
    sb.AppendLine();
    sb.AppendLine("## Summary");
    sb.AppendLine();
    sb.AppendLine("| Kind | Types | Members missing in BL | Types ExampleMod uses |");
    sb.AppendLine("|---|---|---|---|");
    foreach (var g in rows.GroupBy(r => r.Decision.TrimEnd('?', ' ')).OrderBy(g => g.Key))
        sb.AppendLine($"| {g.Key} | {g.Count()} | {g.Sum(r => r.Total - r.Same)} | {g.Count(r => r.Uses > 0)} |");
    sb.AppendLine($"| all | {rows.Count} | {rows.Sum(r => r.Total - r.Same)} | {rows.Count(r => r.Uses > 0)} |");

    foreach (var ns in rows.GroupBy(r => r.Type.Namespace).OrderBy(g => g.Key, StringComparer.Ordinal))
    {
        sb.AppendLine();
        sb.AppendLine($"## {ns.Key}");
        sb.AppendLine();
        sb.AppendLine("| Type | Kind | BL | Game | ExampleMod | Note |");
        sb.AppendLine("|---|---|---|---|---|---|");
        foreach (Row r in ns.OrderBy(r => r.Type.Name, StringComparer.Ordinal))
        {
            string bl = r.Our == null ? "no type" : $"{r.Same}/{r.Total}{(r.Overload > 0 ? $" +{r.Overload}" : "")}{(r.OurNote.Length > 0 ? $" ({r.OurNote})" : "")}";
            string game = r.Game == null ? "no" : r.GameNote.Length > 0 ? $"yes ({r.GameNote})" : "yes";
            string kind = r.Type.Kind == "enum" || r.Type.Kind == "struct" || r.Type.Kind == "interface" || r.Type.Kind == "delegate" ? $" {r.Type.Kind}" : "";
            sb.AppendLine($"| `{r.Type.Name}`{kind} | {r.Decision} | {bl} | {game} | {(r.Uses > 0 ? r.Uses.ToString() : "")} | {r.Note} |");
        }
    }

    File.WriteAllText(reportFile, sb.ToString().Replace("\r\n", "\n"));
}

string Suggest(TypeInfo type, TypeInfo? our, TypeInfo? game, int same, int total)
{
    if (our != null && same == total) return "done";
    if (!type.Native) return "1 copy ?";
    if (game != null) return "2 game ?";
    return "3 native ?";
}

static bool Callable(TypeInfo set, Member m)
{
    if (set.All.ContainsKey(m.Signature)) return true;
    if (m.Params == null) return false;

    foreach (Member other in set.All.Values)
    {
        if (other.Name != m.Name || other.Kind != m.Kind || other.Params == null) continue;
        if (other.Params.Length < m.Params.Length || other.Required > m.Params.Length) continue;
        if (other.Params.Take(m.Params.Length).SequenceEqual(m.Params)) return true;
    }

    return false;
}

static (string Kind, string Note)? Decide(Dictionary<string, (string Kind, string Note)> decisions, string fullName)
{
    if (decisions.TryGetValue(fullName, out var exact)) return exact;

    string? best = decisions.Keys
        .Where(k => k.EndsWith('*') && fullName.StartsWith(k[..^1], StringComparison.Ordinal))
        .OrderByDescending(k => k.Length)
        .FirstOrDefault();

    return best == null ? null : decisions[best];
}

static int Count(string text, string pattern) => text.Length == 0 ? 0 : Regex.Matches(text, pattern).Count;

static TypeInfo? Find(Dictionary<string, TypeInfo> set, TypeInfo type, out string note)
{
    note = "";
    if (set.TryGetValue(type.FullName, out var exact)) return exact;

    var byName = set.Values.Where(t => t.Name == type.Name && t.Kind != "delegate").ToList();
    if (byName.Count == 0) return null;

    TypeInfo pick = byName.OrderBy(t => t.Namespace.Length).First();
    note = $"in {pick.Namespace}";
    return pick;
}

static Dictionary<string, (string Kind, string Note)> ReadDecisions(string file)
{
    var result = new Dictionary<string, (string, string)>();
    if (!File.Exists(file)) return result;

    foreach (string line in File.ReadAllLines(file))
    {
        if (line.StartsWith('#') || !line.Contains('|')) continue;

        string[] parts = line.Split('|', 3);
        result[parts[0].Trim()] = (parts[1].Trim(), parts.Length > 2 ? parts[2].Trim() : "");
    }

    return result;
}

static IEnumerable<(string, string)> DumpSections(string file)
{
    var current = new StringBuilder();
    string? ns = null;

    foreach (string line in File.ReadLines(file))
    {
        if (line.StartsWith("// Namespace: "))
        {
            if (ns != null) yield return ("dump:" + ns, $"namespace {ns} {{\n{current}\n}}");

            string next = line["// Namespace: ".Length..].Trim();
            ns = next.StartsWith("Microsoft.Xna.Framework") ? next : null;
            current.Clear();
            continue;
        }

        if (ns != null) current.AppendLine(line);
    }

    if (ns != null) yield return ("dump:" + ns, $"namespace {ns} {{\n{current}\n}}");
}

static Dictionary<string, TypeInfo> Scan(IEnumerable<(string Path, string Text)> files, bool strictPublic)
{
    var types = new Dictionary<string, TypeInfo>();
    string[] nativeMarks = { "FNA3D.", "FAudio.", "SDL.", "SDL2.", "SDL3.", "FNAPlatform.", "Theorafile.", "SDL2_FNAPlatform" };

    foreach (var (path, text) in files)
    {
        var tree = CSharpSyntaxTree.ParseText(text, new CSharpParseOptions(LanguageVersion.Preview));
        bool native = nativeMarks.Any(text.Contains);

        foreach (var decl in tree.GetRoot().DescendantNodes().OfType<MemberDeclarationSyntax>())
        {
            if (decl is not (BaseTypeDeclarationSyntax or DelegateDeclarationSyntax)) continue;
            if (!IsVisibleType(decl)) continue;

            string ns = decl.Ancestors().OfType<BaseNamespaceDeclarationSyntax>().Select(n => n.Name.ToString()).Reverse().DefaultIfEmpty("").Aggregate((a, b) => a + "." + b);
            if (!ns.StartsWith("Microsoft.Xna.Framework")) continue;

            string name = string.Join(".", decl.AncestorsAndSelf().OfType<BaseTypeDeclarationSyntax>().Select(TypeName).Reverse());
            if (decl is DelegateDeclarationSyntax del) name = (name.Length > 0 ? name + "." : "") + del.Identifier.Text;
            if (name.Contains('<') && name.Contains(">c")) continue;

            string full = ns + "." + name;
            if (!types.TryGetValue(full, out var type))
            {
                type = new TypeInfo(ns, name, Kind(decl));
                types[full] = type;
            }

            type.Native |= native;
            if (decl is not BaseTypeDeclarationSyntax typeDecl) continue;

            if (typeDecl.BaseList != null)
                type.Bases.AddRange(typeDecl.BaseList.Types.Select(b => Simple(b.Type.ToString())));

            bool isInterface = typeDecl is InterfaceDeclarationSyntax;

            if (typeDecl is EnumDeclarationSyntax e)
            {
                foreach (var em in e.Members) type.Add(new Member("value", em.Identifier.Text, em.Identifier.Text));
                continue;
            }

            foreach (var m in ((TypeDeclarationSyntax)typeDecl).Members)
            {
                if (m is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax) continue;
                if (!isInterface && !IsPublic(m.Modifiers, strictPublic)) continue;

                foreach (Member member in Describe(m)) type.Add(member);
            }
        }
    }

    return types;
}

static bool IsVisibleType(MemberDeclarationSyntax decl)
{
    foreach (var node in decl.AncestorsAndSelf().OfType<MemberDeclarationSyntax>())
    {
        if (node is BaseNamespaceDeclarationSyntax) break;

        var mods = node.Modifiers;
        if (!mods.Any(SyntaxKind.PublicKeyword) && !mods.Any(SyntaxKind.ProtectedKeyword)) return false;
        if (mods.Any(SyntaxKind.PrivateKeyword)) return false;
    }

    return true;
}

static bool IsPublic(SyntaxTokenList mods, bool strictPublic)
{
    if (mods.Any(SyntaxKind.PublicKeyword)) return true;
    if (mods.Any(SyntaxKind.ProtectedKeyword) && !mods.Any(SyntaxKind.PrivateKeyword) && !(mods.Any(SyntaxKind.InternalKeyword) && !strictPublic)) return true;
    return false;
}

static string TypeName(BaseTypeDeclarationSyntax t) =>
    t is TypeDeclarationSyntax { TypeParameterList: { } tp } ? $"{t.Identifier.Text}`{tp.Parameters.Count}" : t.Identifier.Text;

static string Kind(MemberDeclarationSyntax decl) => decl switch
{
    StructDeclarationSyntax => "struct",
    RecordDeclarationSyntax => "record",
    InterfaceDeclarationSyntax => "interface",
    EnumDeclarationSyntax => "enum",
    DelegateDeclarationSyntax => "delegate",
    _ => "class",
};

static IEnumerable<Member> Describe(MemberDeclarationSyntax m)
{
    switch (m)
    {
        case MethodDeclarationSyntax method:
            string arity = method.TypeParameterList is { } tp ? $"`{tp.Parameters.Count}" : "";
            yield return new Member(Static(m, "method"), method.Identifier.Text + arity, $"{method.Identifier.Text}{arity}({Params(method.ParameterList)})", ParamList(method.ParameterList), Required(method.ParameterList));
            break;
        case ConstructorDeclarationSyntax ctor when !ctor.Modifiers.Any(SyntaxKind.StaticKeyword):
            yield return new Member("ctor", ".ctor", $".ctor({Params(ctor.ParameterList)})", ParamList(ctor.ParameterList), Required(ctor.ParameterList));
            break;
        case OperatorDeclarationSyntax op:
            yield return new Member("operator", "op " + op.OperatorToken.Text, $"operator {op.OperatorToken.Text}({Params(op.ParameterList)})");
            break;
        case ConversionOperatorDeclarationSyntax conv:
            yield return new Member("operator", "op " + conv.ImplicitOrExplicitKeyword.Text, $"{conv.ImplicitOrExplicitKeyword.Text} operator {Simple(conv.Type.ToString())}({Params(conv.ParameterList)})");
            break;
        case PropertyDeclarationSyntax prop:
            yield return new Member(Static(m, "property"), prop.Identifier.Text, prop.Identifier.Text);
            break;
        case IndexerDeclarationSyntax indexer:
            yield return new Member("indexer", "this[]", $"this[{Params(indexer.ParameterList)}]");
            break;
        case EventDeclarationSyntax ev:
            yield return new Member("event", ev.Identifier.Text, ev.Identifier.Text);
            break;
        case EventFieldDeclarationSyntax evf:
            foreach (var v in evf.Declaration.Variables) yield return new Member("event", v.Identifier.Text, v.Identifier.Text);
            break;
        case FieldDeclarationSyntax field:
            foreach (var v in field.Declaration.Variables) yield return new Member(Static(m, field.Modifiers.Any(SyntaxKind.ConstKeyword) ? "const" : "field"), v.Identifier.Text, v.Identifier.Text);
            break;
    }
}

static string Static(MemberDeclarationSyntax m, string kind) => m.Modifiers.Any(SyntaxKind.StaticKeyword) && kind != "const" ? "static " + kind : kind;

static string Params(BaseParameterListSyntax list) => string.Join(", ", ParamList(list));

static string[] ParamList(BaseParameterListSyntax list) => list.Parameters.Select(p =>
{
    string mod = string.Join(" ", p.Modifiers.Where(t => t.IsKind(SyntaxKind.RefKeyword) || t.IsKind(SyntaxKind.OutKeyword) || t.IsKind(SyntaxKind.InKeyword)).Select(t => t.Text));
    string type = Simple(p.Type?.ToString() ?? "?");
    return mod.Length > 0 ? $"{mod} {type}" : type;
}).ToArray();

static int Required(BaseParameterListSyntax list) => list.Parameters.Count(p => p.Default == null && !p.Modifiers.Any(SyntaxKind.ParamsKeyword));

static string Simple(string type)
{
    string t = type.Replace("global::", "").Replace(" ", "");
    t = Regex.Replace(t, @"\b(?:[A-Za-z_]\w*\.)+(?=[A-Za-z_]\w*)", "");
    t = Regex.Replace(t, @"\bGameArray<([^<>]+)>", "$1[]");
    t = Regex.Replace(t, @"\b(?:GameNullable|Nullable)<([^<>]+)>", "$1");
    t = t.Replace("?", "");
    var aliases = new Dictionary<string, string>
    {
        ["Int32"] = "int", ["UInt32"] = "uint", ["Int16"] = "short", ["UInt16"] = "ushort", ["Int64"] = "long", ["UInt64"] = "ulong",
        ["Single"] = "float", ["Double"] = "double", ["Boolean"] = "bool", ["String"] = "string", ["Byte"] = "byte", ["SByte"] = "sbyte",
        ["Char"] = "char", ["Object"] = "object", ["IntPtr"] = "nint", ["UIntPtr"] = "nuint", ["Void"] = "void",
    };
    return Regex.Replace(t, @"\b[A-Z]\w*\b", m => aliases.GetValueOrDefault(m.Value, m.Value));
}

static void Flatten(Dictionary<string, TypeInfo> set)
{
    var byName = set.Values.GroupBy(t => t.Name).ToDictionary(g => g.Key, g => g.ToList());

    foreach (TypeInfo type in set.Values) Fill(type, new HashSet<TypeInfo>());

    void Fill(TypeInfo type, HashSet<TypeInfo> seen)
    {
        if (type.Flattened || !seen.Add(type)) return;

        foreach (string b in type.Bases)
        {
            if (!byName.TryGetValue(b, out var candidates)) continue;

            TypeInfo baseType = candidates.FirstOrDefault(c => c.Namespace == type.Namespace) ?? candidates[0];
            if (baseType.Kind == "interface" && type.Kind != "interface") continue;

            Fill(baseType, seen);
            type.Native |= baseType.Native;
            foreach (var (sig, member) in baseType.All)
                if (member.Kind != "ctor" && !member.Kind.StartsWith("static") && member.Kind != "operator") type.All.TryAdd(sig, member);
            type.Names.UnionWith(baseType.All.Values.Where(m => m.Kind != "ctor").Select(m => m.Name));
        }

        type.Flattened = true;
    }
}

sealed record Member(string Kind, string Name, string Signature, string[]? Params = null, int Required = 0);

sealed class TypeInfo(string ns, string name, string kind)
{
    public string Namespace { get; } = ns;
    public string Name { get; } = name;
    public string Kind { get; } = kind;
    public string FullName => Namespace + "." + Name;
    public List<string> Bases { get; } = new();
    public Dictionary<string, Member> All { get; } = new();
    public HashSet<string> Names { get; } = new();
    public bool Native { get; set; }
    public bool Flattened { get; set; }

    public void Add(Member m)
    {
        All.TryAdd(m.Signature, m);
        Names.Add(m.Name);
    }
}

sealed record Row(TypeInfo Type, TypeInfo? Our, TypeInfo? Game, string OurNote, string GameNote, int Same, int Overload, int Total, int Uses, string Decision, string Note);
