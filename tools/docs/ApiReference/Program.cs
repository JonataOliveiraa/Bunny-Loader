Directory.CreateDirectory(outDir);
foreach (string old in Directory.GetFiles(outDir, "API-*.md"))
    File.Delete(old);
foreach (Group group in groups)
    WritePage(group, pages[group.File]);
WriteIndex();
File.WriteAllLines(Path.Combine(root, "tools/docs/ApiReference/missing.txt"), missing.Select(line =>
