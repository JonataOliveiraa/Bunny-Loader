    public static Group Of(TypeInfo type)
    {
        if (type.Namespace.StartsWith("BunnyLoader")) return All.First(g => g.File == "API-Interop");
        string name = type.Name;
        return All.First(g => Regex.IsMatch(name, g.Pattern));
    }

