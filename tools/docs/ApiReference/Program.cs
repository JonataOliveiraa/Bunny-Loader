Dictionary<string, TypeInfo> theirTypes = Scan(theirs, true);
Dictionary<string, TypeInfo> gameTypes = Scan(args[1], true);
Dictionary<string, string> patches = Directory.GetFiles(theirs, "*.patch", SearchOption.AllDirectories)
    .GroupBy(f => Path.GetFileName(f).Split('.')[0])
    .ToDictionary(g => g.Key, g => string.Concat(g.SelectMany(File.ReadLines).Where(l => l.StartsWith('+'))));
Dictionary<string, string> notes = new();
if (File.Exists(notesFile))
    foreach (string line in File.ReadAllLines(notesFile).Where(l => l.Contains('|') && !l.StartsWith('#')))
        notes[line[..line.IndexOf('|')].Trim()] = line[(line.IndexOf('|') + 1)..].Trim();

var groups = Groups.All;
var pages = groups.ToDictionary(g => g.File, _ => new List<TypeInfo>());
var documented = ourTypes.Values.Where(t => IsDocumented(t.FullName)).OrderBy(t => t.Name, StringComparer.Ordinal).ToList();
foreach (TypeInfo type in documented)
    pages[Groups.Of(type).File].Add(type);

