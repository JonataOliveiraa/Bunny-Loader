bool IsDocumented(string name)
{
    if (name.Contains(".Core.") || name.StartsWith("Terraria.ModLoader.Core")) return false;
    if (Regex.IsMatch(name, @"^BunnyLoader\.(Interop\.)?(Abi|CallFrame|DrawCapture|GameArrayBuilder|GameConfiguration|GameDelegates|GameInterop|GameTipData|GameTipID|Hook|Hooks\.HookChain|Hooks\.HookErrors|Layouts|MethodRef|Ret[A-Z0-9].*|StaticRef|VirtualCache)$")) return false;
    return name.StartsWith("Terraria") || name.StartsWith("ReLogic") || name.StartsWith("Microsoft.Xna") || name.StartsWith("BunnyLoader.Interop") || name.StartsWith("BunnyLoader.Hooks");
}

TypeInfo? GameTwin(TypeInfo type) => gameTypes.GetValueOrDefault(type.FullName) ?? gameTypes.Values.FirstOrDefault(t => t.Name == (type.Name == "UtilsExtensions" ? "Utils" : type.Name) && t.Namespace.StartsWith("Terraria"));

TypeInfo? Twin(TypeInfo type) => theirTypes.GetValueOrDefault(type.FullName) ?? theirTypes.Values.FirstOrDefault(t => t.Name == type.Name && t.Namespace.StartsWith("Terraria"));

string Describe(string key, string? fromTml)
{
    string text = notes.GetValueOrDefault(key) ?? fromTml ?? Pattern(key) ?? "";
    if (notes.TryGetValue(key + "~", out string? phone))
        text = (text.Length > 0 ? text + " " : "") + "**Phone:** " + phone;
    return text;
}

void WritePage(Group group, List<TypeInfo> types)
{
    var text = new StringBuilder();
    text.Append($"> [API reference](API-Reference) · generated by `tools/docs/ApiReference`, do not edit by hand\n\n{group.Intro}\n\n");
    foreach (TypeInfo type in types)
        WriteType(text, type);
    File.WriteAllText(Path.Combine(outDir, group.File + ".md"), text.ToString(), new UTF8Encoding(false));
}

void WriteType(StringBuilder text, TypeInfo type)
{
    TypeInfo? twin = Twin(type);
    TypeInfo? game = GameTwin(type);
    string description = Describe(type.FullName, twin?.Summary);
    if (description.Length == 0) missing.Add(type.FullName);
    text.Append($"## {type.Name}\n\n`{type.Kind} {type.FullName}`{(type.Base.Length > 0 ? $" : `{type.Base}`" : "")}{(twin == null && game == null ? " · **only in Bunny Loader**" : "")}\n\n");
    if (description.Length > 0) text.Append(description).Append("\n\n");
    if (type.Members.Count == 0 && twin == null && game == null) return;
    if (IsCompact(type))
    {
        counts.Total += type.Members.Count;
        counts.Same += type.Members.Count(m => twin?.Members.Any(o => o.Name == m.Name) == true || game?.Members.Any(o => o.Name == m.Name) == true);
        counts.Ours += type.Members.Count(m => twin?.Members.Any(o => o.Name == m.Name) != true && game?.Members.Any(o => o.Name == m.Name) != true);
        text.Append(type.Kind == "enum" ? "Values: " : "Members: ").Append(string.Join(", ", type.Members.Select(m => $"`{m.Name}`"))).Append("\n\n");
        return;
    }
    text.Append("| Member | Kind | tModLoader | What it does |\n|---|---|---|---|\n");
    var seen = new HashSet<string>();
    foreach (Member member in type.Members)
    {
        seen.Add(member.Name);
        Member? same = twin?.Members.FirstOrDefault(m => m.Name == member.Name && m.Key == member.Key) ?? game?.Members.FirstOrDefault(m => m.Name == member.Name && m.Key == member.Key);
        Member? named = same ?? twin?.Members.FirstOrDefault(m => m.Name == member.Name) ?? game?.Members.FirstOrDefault(m => m.Name == member.Name);
        bool inPatch = named == null && patches.TryGetValue(type.Name.Split('.')[0], out string? patch) && Regex.IsMatch(patch, $@"\b{Regex.Escape(member.Name)}\b");
        string status;
        bool implicitConstructor = member.Signature == $"new {type.Name.Split('.').Last()}()" && (twin != null || game != null);
        if (Library(type) is { } library) { status = library; counts.Same++; }
        else if (same != null || inPatch || implicitConstructor) { status = "same"; counts.Same++; }
        else if (named != null) { status = "differs"; counts.Differs++; }
        else { status = "**only here**"; counts.Ours++; }
        counts.Total++;
        string key = $"{type.FullName}.{member.Name}";
        string what = Describe(key, (same ?? named)?.Summary ?? member.Summary ?? Sibling(type, member) ?? Ancestor(type, twin, member));
        if (what.Length == 0) what = Trivial(type, member);
        if (what.Length == 0 && member.Kind is not ("const" or "value")) missing.Add($"{key}  {member.Signature}");
        if (status == "differs") what = (what + $" tML: `{Cell(named!.Signature)}`").Trim();
        text.Append($"| `{Cell(member.Signature)}` | {member.Kind} | {status} | {Cell(what)} |\n");
    }
    int runners = 0;
    if (twin != null && !Groups.SkipMissing(type.Name))
    {
        foreach (Member member in twin.Members.Where(m => !seen.Contains(m.Name) && !m.Obsolete && m.Kind is not ("override" or "constructor") && !m.Signature.StartsWith("new ") && m.Name != "AddModHook" && !Inherits(type, m.Name)).GroupBy(m => m.Name).Select(g => g.First()))
        {
            if (type.Name.EndsWith("Loader") && IsHookName(type, member.Name))
            {
                runners++;
                continue;
            }
            counts.NotHere++;
            counts.Total++;
            string what = notes.GetValueOrDefault($"{type.FullName}.{member.Name}!") ?? Pattern($"{type.FullName}.{member.Name}!") ?? member.Summary ?? Sibling(type, member) ?? Ancestor(type, twin, member) ?? "";
            text.Append($"| `{Cell(member.Signature)}` | {member.Kind} | **not here** | {Cell(what)} |\n");
        }
    }
    text.Append('\n');
    if (runners > 0)
    {
        counts.Runners += runners;
        text.Append($"tModLoader's `{type.Name}` also has {runners} public methods that only run the hooks of the same name. Here those runners are internal. Override the hook in your class instead.\n\n");
    }
}

static string? Library(TypeInfo type) => type.Namespace.StartsWith("Microsoft.Xna") ? "XNA" : type.Name == "Asset" ? "ReLogic" : null;

bool IsHookName(TypeInfo type, string member)
{
    string stem = Regex.Replace(type.Name, "Loader$", "");
    foreach (string candidate in new[] { "Mod" + stem, "Global" + stem, "Mod" + stem + "Style", stem })
        if (ourTypes.Values.Any(t => t.Name == candidate && t.Namespace.StartsWith("Terraria") && (t.Members.Any(m => m.Name == member) || Inherits(t, member))))
            return true;
    return false;
}

string? Ancestor(TypeInfo type, TypeInfo? twin, Member member)
{
    foreach (TypeInfo? start in new[] { type, twin })
    {
        TypeInfo? current = start;
        for (int depth = 0; current != null && depth < 8; depth++)
        {
            string clean = Regex.Replace(current.Base, "<.*>$", "");
            if (clean.Length == 0) break;
            current = theirTypes.Values.FirstOrDefault(t => t.Name == clean) ?? ourTypes.Values.FirstOrDefault(t => t.Name == clean);
            string? found = current?.Members.FirstOrDefault(m => m.Name == member.Name && m.Summary != null)?.Summary;
            if (found != null) return found;
        }
    }
    return null;
}

bool Inherits(TypeInfo type, string member)
{
    string baseName = type.Base;
    for (int depth = 0; depth < 8 && baseName.Length > 0; depth++)
    {
        string clean = Regex.Replace(baseName, "<.*>$", "");
        TypeInfo? parent = ourTypes.Values.FirstOrDefault(t => t.Name == clean);
        if (parent == null) return false;
        if (parent.Members.Any(m => m.Name == member)) return true;
        baseName = parent.Base;
    }
    return false;
}

string? Pattern(string key)
{
    foreach ((string pattern, string value) in notes)
    {
        if (!pattern.Contains('*')) continue;
        string regex = "^" + Regex.Escape(pattern).Replace("\\*\\*", ".+").Replace("\\*", "[A-Za-z0-9_]*") + "$";
        if (Regex.IsMatch(key, regex)) return value;
    }
    return null;
}

static bool IsCompact(TypeInfo type)
{
    if (type.Kind == "enum") return true;
    if (type.Members.Count < 8) return false;
    int plain = type.Members.Count(m => m.Summary == null && (m.Kind is "const" or "static field" or "value"));
    return plain * 5 >= type.Members.Count * 4;
}

string? Sibling(TypeInfo type, Member member)
{
    string name = type.Name;
    string stem = Regex.Replace(name, "^(Mod|Global)|Loader$", "");
    foreach (string candidate in new[] { "Mod" + stem, "Global" + stem, stem + "Loader", stem })
    {
        if (candidate == name) continue;
        foreach (var table in new[] { theirTypes, ourTypes })
        {
            TypeInfo? other = table.Values.FirstOrDefault(t => t.Name == candidate && t.Namespace.StartsWith("Terraria"));
            for (int depth = 0; other != null && depth < 6; depth++)
            {
                string? found = other.Members.FirstOrDefault(m => m.Name == member.Name && m.Summary != null)?.Summary;
                if (found != null) return found;
                string parent = Regex.Replace(other.Base, "<.*>$", "");
                other = parent.Length == 0 ? null : table.Values.FirstOrDefault(t => t.Name == parent);
            }
        }
    }
    return null;
}

static string Trivial(TypeInfo type, Member member)
{
    string simple = type.Name.Split('.').Last();
    return member.Name switch
    {
        "new" => "Creates an instance.",
        "ToString" => "The text form of this value.",
        "Equals" => "Whether both hold the same value.",
        "GetHashCode" => "The hash of this value.",
        "GetEnumerator" => "Walks the items in `foreach`.",
        "Clone" => "A copy of this object.",
        "SetupContent" => "Called by the loader to run `SetStaticDefaults`. Mods do not call it.",
        "Register" => "Called by the loader to register this content. Mods do not call it.",
        _ => "",
    };
}

string StartSection()
{
    var text = new StringBuilder("## The classes you build a mod with\n\nCreate a class that derives from one of these and Bunny Loader finds it by itself. Click a name to see all its hooks.\n");
    var listed = new HashSet<string>();
    foreach (string line in File.ReadAllLines(Path.Combine(root, "tools/docs/ApiReference/start.txt")).Where(l => l.Trim().Length > 0))
    {
        if (line.StartsWith('#'))
        {
            text.Append($"\n### {line[1..].Trim()}\n\n| Class | What you use it for |\n|---|---|\n");
            continue;
        }
        string name = line[..line.IndexOf('|')];
        Group group = groups.First(g => pages[g.File].Any(t => t.Name == name));
        listed.Add(name);
        text.Append($"| [{name}]({group.File}#{name.ToLowerInvariant()}) | {Cell(line[(line.IndexOf('|') + 1)..])} |\n");
    }
    missing.AddRange(documented.Where(t => Regex.IsMatch(t.Name, "^(Mod|Global)[A-Z][A-Za-z]*$") && t.Kind.Contains("class") && !listed.Contains(t.Name) && !Groups.NotStarting(t.Name)).Select(t => t.FullName + " is not in start.txt"));
    return text.ToString();
}

void WriteIndex()
{
    var text = new StringBuilder();
    text.Append(File.ReadAllText(Path.Combine(root, "tools/docs/ApiReference/intro.md")).Replace("\r\n", "\n").Replace("{{START}}", StartSection()).TrimEnd()).Append("\n\n");
    text.Append($"**{documented.Count} classes, {counts.Total} members:** {counts.Same} the same as tModLoader or the PC game, {counts.Differs} with a different signature, {counts.Ours} only here, {counts.NotHere} not here. tModLoader's loaders have {counts.Runners} more methods that only run hooks: each page counts them under its loader.\n\n");
    foreach (Group group in groups)
    {
        if (pages[group.File].Count == 0) continue;
        text.Append($"## [{group.Title}]({group.File})\n\n| Class | Kind | In tModLoader | What it is |\n|---|---|---|---|\n");
        foreach (TypeInfo type in pages[group.File])
        {
            TypeInfo? twin = Twin(type) ?? GameTwin(type);
            string what = Describe(type.FullName, twin?.Summary);
            int cut = what.IndexOf(". ", StringComparison.Ordinal);
            if (cut > 0) what = what[..(cut + 1)];
            text.Append($"| [{type.Name}]({group.File}#{type.Name.ToLowerInvariant().Replace(".", "")}) | {type.Kind} | {(twin != null ? "yes" : "**no**")} | {Cell(what)} |\n");
        }
        text.Append('\n');
    }
    var absent = theirTypes.Values
        .Where(t => !ourTypes.Values.Any(o => o.Name == t.Name) && !Groups.SkipAbsent(t) && t.IsPublic)
        .OrderBy(t => t.FullName, StringComparer.Ordinal).ToList();
    text.Append("## In tModLoader, not here\n\nPublic classes of tModLoader's mod API that Bunny Loader does not have. Names are under `Terraria.ModLoader`.\n\n| Classes | Why |\n|---|---|\n");
    foreach (var row in absent.GroupBy(t => notes.GetValueOrDefault(t.FullName + "!") ?? Pattern(t.FullName + "!") ?? t.Summary ?? "").OrderBy(g => g.Min(t => t.FullName), StringComparer.Ordinal))
    {
        string names = string.Join(", ", row.Select(t => $"`{t.FullName.Replace("Terraria.ModLoader.", "")}`"));
        text.Append($"| {names} | {Cell(row.Key)} |\n");
    }
    File.WriteAllText(Path.Combine(outDir, "API-Reference.md"), text.ToString(), new UTF8Encoding(false));
}

static string Cell(string text) => text.Replace("|", "\\|").Replace("\r", " ").Replace("\n", " ").Trim();

static Dictionary<string, TypeInfo> Scan(string folder, bool theirs)
{
    var types = new Dictionary<string, TypeInfo>();
    var options = new CSharpParseOptions(LanguageVersion.Latest, DocumentationMode.Parse);
    foreach (string file in Directory.GetFiles(folder, "*.cs", SearchOption.AllDirectories))
    {
        string path = file.Replace('\\', '/');
        if (path.Contains("/obj/") || path.Contains("/bin/")) continue;
        SyntaxNode syntax = CSharpSyntaxTree.ParseText(File.ReadAllText(file), options).GetRoot();
        foreach (BaseTypeDeclarationSyntax type in syntax.DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
            Add(types, type);
        foreach (DelegateDeclarationSyntax type in syntax.DescendantNodes().OfType<DelegateDeclarationSyntax>().Where(d => d.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax))
        {
            string name = NamespaceOf(type) + "." + type.Identifier.Text;
            if (!types.ContainsKey(name))
                types[name] = new TypeInfo(name, type.Identifier.Text, NamespaceOf(type), "delegate") { Summary = Docs(type), IsPublic = type.Modifiers.Any(SyntaxKind.PublicKeyword), Base = "" };
        }
    }
    return types.Where(t => t.Value.IsPublic).ToDictionary(t => t.Key, t => t.Value);
}

static string NamespaceOf(SyntaxNode node)
{
    var parts = new List<string>();
    foreach (BaseNamespaceDeclarationSyntax space in node.Ancestors().OfType<BaseNamespaceDeclarationSyntax>())
        parts.Insert(0, space.Name.ToString());
    return string.Join('.', parts);
}

static string QualifiedName(BaseTypeDeclarationSyntax type)
{
    var parts = new List<string> { type.Identifier.Text };
    foreach (BaseTypeDeclarationSyntax outer in type.Ancestors().OfType<BaseTypeDeclarationSyntax>())
        parts.Insert(0, outer.Identifier.Text);
    return string.Join('.', parts);
}

static void Add(Dictionary<string, TypeInfo> types, BaseTypeDeclarationSyntax type)
{
    string qualified = QualifiedName(type);
    string space = NamespaceOf(type);
    string full = space.Length > 0 ? space + "." + qualified : qualified;
    if (!types.TryGetValue(full, out TypeInfo? info))
        types[full] = info = new TypeInfo(full, qualified, space, KindOf(type));
    bool outerPublic = type.Ancestors().OfType<BaseTypeDeclarationSyntax>().All(a => a.Modifiers.Any(SyntaxKind.PublicKeyword) || a.Modifiers.Any(SyntaxKind.PartialKeyword));
    if (type.Modifiers.Any(SyntaxKind.PublicKeyword) && outerPublic) info.IsPublic = true;
    info.Summary ??= Docs(type);
    if (info.Base.Length == 0 && type.BaseList != null) info.Base = Short(type.BaseList.Types[0].ToString());
    switch (type)
    {
        case EnumDeclarationSyntax values:
            foreach (EnumMemberDeclarationSyntax value in values.Members)
                info.Add(new Member(value.Identifier.Text, value.Identifier.Text, "value", value.Identifier.Text) { Summary = Docs(value) });
            break;
        case TypeDeclarationSyntax body:
            bool open = type is InterfaceDeclarationSyntax;
            foreach (MemberDeclarationSyntax member in body.Members)
                AddMember(info, member, open, qualified);
            break;
    }
}

static string KindOf(BaseTypeDeclarationSyntax type) => type switch
{
    InterfaceDeclarationSyntax => "interface",
    EnumDeclarationSyntax => "enum",
    StructDeclarationSyntax => "struct",
    RecordDeclarationSyntax => "record",
    _ => type.Modifiers.Any(SyntaxKind.StaticKeyword) ? "static class" : type.Modifiers.Any(SyntaxKind.AbstractKeyword) ? "abstract class" : "class",
};

static void AddMember(TypeInfo info, MemberDeclarationSyntax member, bool open, string qualified)
{
    if (member is BaseTypeDeclarationSyntax) return;
    SyntaxTokenList modifiers = member.Modifiers;
    bool visible = open || modifiers.Any(SyntaxKind.PublicKeyword) || (modifiers.Any(SyntaxKind.ProtectedKeyword) && !modifiers.Any(SyntaxKind.PrivateKeyword) && !modifiers.Any(SyntaxKind.InternalKeyword));
    if (!visible || modifiers.Any(SyntaxKind.OverrideKeyword) && modifiers.Any(SyntaxKind.SealedKeyword)) return;
    bool obsolete = member.AttributeLists.SelectMany(a => a.Attributes).Any(a => a.Name.ToString().Contains("Obsolete"));
    string prefix = modifiers.Any(SyntaxKind.StaticKeyword) ? "static " : "";
    string flavor = modifiers.Any(SyntaxKind.VirtualKeyword) || modifiers.Any(SyntaxKind.AbstractKeyword) || open ? "hook" : modifiers.Any(SyntaxKind.OverrideKeyword) ? "override" : "";
    string summary = Docs(member);
    switch (member)
    {
        case MethodDeclarationSyntax m:
            string parameters = string.Join(", ", m.ParameterList.Parameters.Select(Parameter));
            string key = string.Join(",", m.ParameterList.Parameters.Select(p => Short(Modifier(p) + (p.Type?.ToString() ?? ""))));
            info.Add(new Member(m.Identifier.Text, $"{Short(m.ReturnType.ToString())} {m.Identifier.Text}{m.TypeParameterList}({parameters})", (flavor.Length > 0 ? flavor : prefix + "method").Trim(), key) { Summary = summary, Obsolete = obsolete });
            break;
        case PropertyDeclarationSyntax p:
            info.Add(new Member(p.Identifier.Text, $"{Short(p.Type.ToString())} {p.Identifier.Text}", (flavor.Length > 0 ? flavor : prefix + "property").Trim(), Short(p.Type.ToString())) { Summary = summary, Obsolete = obsolete });
            break;
        case FieldDeclarationSyntax f:
            foreach (VariableDeclaratorSyntax variable in f.Declaration.Variables)
                info.Add(new Member(variable.Identifier.Text, $"{Short(f.Declaration.Type.ToString())} {variable.Identifier.Text}", modifiers.Any(SyntaxKind.ConstKeyword) ? "const" : (prefix + "field").Trim(), Short(f.Declaration.Type.ToString())) { Summary = summary, Obsolete = obsolete });
            break;
        case EventDeclarationSyntax e:
            info.Add(new Member(e.Identifier.Text, $"{Short(e.Type.ToString())} {e.Identifier.Text}", (prefix + "event").Trim(), Short(e.Type.ToString())) { Summary = summary, Obsolete = obsolete });
            break;
        case EventFieldDeclarationSyntax e:
            foreach (VariableDeclaratorSyntax variable in e.Declaration.Variables)
                info.Add(new Member(variable.Identifier.Text, $"{Short(e.Declaration.Type.ToString())} {variable.Identifier.Text}", (prefix + "event").Trim(), Short(e.Declaration.Type.ToString())) { Summary = summary, Obsolete = obsolete });
            break;
        case ConstructorDeclarationSyntax c:
            string ctor = string.Join(", ", c.ParameterList.Parameters.Select(Parameter));
            info.Add(new Member("new", $"new {c.Identifier.Text}({ctor})", "constructor", string.Join(",", c.ParameterList.Parameters.Select(p => Short(p.Type?.ToString() ?? "")))) { Summary = summary, Obsolete = obsolete });
            break;
        case IndexerDeclarationSyntax x:
            info.Add(new Member("this[]", $"{Short(x.Type.ToString())} this[{string.Join(", ", x.ParameterList.Parameters.Select(Parameter))}]", "indexer", Short(x.Type.ToString())) { Summary = summary, Obsolete = obsolete });
            break;
    }
}

static string Modifier(ParameterSyntax p) => p.Modifiers.Count > 0 ? p.Modifiers[0].Text + " " : "";

static string Parameter(ParameterSyntax p) => $"{Modifier(p)}{Short(p.Type?.ToString() ?? "")} {p.Identifier.Text}";

static string Short(string type)
{
    string clean = type.Replace("global::", "").Replace("?", "").Replace(" ", "");
    clean = Regex.Replace(clean, @"^ref(readonly)?(?=[A-Za-z(])", m => m.Groups[1].Success ? "ref readonly " : "ref ");
    clean = Regex.Replace(clean, @"(?<=[(,])(string|int|bool|float)(?=[a-z])", "$1 ");
    clean = Regex.Replace(clean, @"([A-Za-z_][A-Za-z0-9_]*\.)+([A-Za-z_][A-Za-z0-9_]*)", "$2");
    return clean.Replace(",", ", ");
}

static string? Docs(SyntaxNode node)
{
    string? raw = node.GetLeadingTrivia().Where(t => t.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia)).Select(t => t.ToFullString()).FirstOrDefault();
    if (raw == null) return null;
    string body = Regex.Replace(raw, @"^\s*///\s?", "", RegexOptions.Multiline);
    Match match = Regex.Match(body, "<summary>(.*?)</summary>", RegexOptions.Singleline);
    string text = match.Success ? match.Groups[1].Value : body;
    text = Regex.Replace(text, @"<see\s+cref=""[^""]*?([A-Za-z0-9_]+)(\([^""]*\))?""\s*/>", "`$1`");
    text = Regex.Replace(text, @"<see\s+cref=""[^""]*?([A-Za-z0-9_]+)(\([^""]*\))?""\s*>(.*?)</see>", "$3");
    text = Regex.Replace(text, @"<(paramref|typeparamref)\s+name=""([^""]*)""\s*/>", "`$2`");
    text = Regex.Replace(text, @"<see\s+langword=""([^""]*)""\s*/>", "`$1`");
    text = Regex.Replace(text, @"<c>(.*?)</c>", "`$1`", RegexOptions.Singleline);
    text = Regex.Replace(text, @"<br\s*/>|<para\s*/>|</?para>|</?list[^>]*>|</?item>|</?description>|</?term>", " ");
    text = Regex.Replace(text, @"<[^>]+>", "");
    text = WebUtility.HtmlDecode(text);
    text = Regex.Replace(text, @"\s+", " ").Trim();
    return text.Length == 0 ? null : text;
}

sealed class TypeInfo(string fullName, string name, string space, string kind)
{
    public string FullName { get; } = fullName;
    public string Name { get; } = name;
    public string Namespace { get; } = space;
    public string Kind { get; } = kind;
    public string Base { get; set; } = "";
    public string? Summary { get; set; }
    public bool IsPublic { get; set; }
    public List<Member> Members { get; } = new();

    public void Add(Member member)
    {
        if (!Members.Any(m => m.Name == member.Name && m.Key == member.Key))
            Members.Add(member);
    }
}

sealed class Member(string name, string signature, string kind, string key)
{
    public string Name { get; } = name;
    public string Signature { get; } = signature;
    public string Kind { get; } = kind;
    public string Key { get; } = key;
    public string? Summary { get; set; }
    public bool Obsolete { get; set; }
}

