string theirs = Path.Combine(root, "exmod_tmod/tModLoader/patches/tModLoader/Terraria");
string outDir = Path.Combine(root, "wiki/reference");
string notesFile = Path.Combine(root, "tools/docs/ApiReference/notes.txt");

