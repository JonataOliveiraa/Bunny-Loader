import io
import os
import shutil
import sys

out = sys.argv[1]
count = int(sys.argv[2]) if len(sys.argv) > 2 else 1500
here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.abspath(os.path.join(here, "..", ".."))
texture = os.path.join(repo, "tools", "tests", "csmusicmenu", "BoxItem.png")
api = os.path.join(repo, "app", "build", "csharp", "BunnyLoader", "BunnyLoader.dll").replace("\\", "/")

os.makedirs(os.path.join(out, "src"), exist_ok=True)
for i in range(count):
    shutil.copyfile(texture, os.path.join(out, f"Gen{i:04d}.png"))

with io.open(os.path.join(out, "manifest.json"), "w", encoding="utf-8") as f:
    f.write('''{
  "uid": "a1b2c3d4-0f15-4e00-9a00-150015001500",
  "id": "CsManyItems",
  "name": "Test: many items",
  "version": "1.0.0",
  "author": "test",
  "category": "Utilidade",
  "summary": "Load cost with many ModItem classes.",
  "description": "Generated by tools/startup/genmany.py.",
  "updated": "2026-11-04",
  "blVersion": 3,
  "gameVersion": [301720, 301720],
  "dependencies": []
}
''')

with io.open(os.path.join(out, "src", "CsManyItems.csproj"), "w", encoding="utf-8") as f:
    f.write(f'''<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net10.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>disable</ImplicitUsings>
    <DebugType>none</DebugType>
    <GenerateDependencyFile>false</GenerateDependencyFile>
    <OutDir>$(MSBuildThisFileDirectory)../</OutDir>
    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>
  </PropertyGroup>
  <ItemGroup>
    <Reference Include="BunnyLoader"><HintPath>{api}</HintPath><Private>false</Private></Reference>
  </ItemGroup>
</Project>
''')

parts = ["using Terraria;\nusing Terraria.ID;\nusing Terraria.ModLoader;\nnamespace CsManyItems;\npublic sealed class CsManyItemsMod : Mod { }\n"]
for i in range(count):
    extra = ""
    if i % 5 == 0:
        extra += "    public override bool? UseItem(Player player) { return true; }\n"
    if i % 7 == 0:
        extra += "    public override void HoldItem(Player player) { player.statDefense += 0; }\n"
    if i % 11 == 0:
        extra += "    public override void UpdateInventory(Player player) { }\n"
    parts.append(f"""public sealed class Gen{i:04d} : ModItem
{{
    public override void SetStaticDefaults() {{ Item.ResearchUnlockCount = {i % 100 + 1}; }}
    public override void SetDefaults()
    {{
        Item.width = 20; Item.height = 20; Item.maxStack = 99; Item.value = {i}; Item.rare = {i % 10};
        Item.useStyle = ItemUseStyleID.Swing; Item.useTime = {i % 30 + 10}; Item.useAnimation = {i % 30 + 10};
    }}
{extra}}}
""")
with io.open(os.path.join(out, "src", "CsManyItems.cs"), "w", encoding="utf-8") as f:
    f.write("".join(parts))
