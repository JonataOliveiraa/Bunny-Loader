import argparse
import io
import os
import random
import subprocess
import uuid

from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.abspath(os.path.join(here, "..", ".."))
api = os.path.join(repo, "app", "build", "csharp", "BunnyLoader", "BunnyLoader.dll").replace("\\", "/")

parser = argparse.ArgumentParser()
parser.add_argument("out")
parser.add_argument("prefix")
parser.add_argument("--mods", type=int, default=1)
parser.add_argument("--items", type=int, default=10)
parser.add_argument("--menu", type=int, default=0)
parser.add_argument("--menu-size", type=int, default=512)
args = parser.parse_args()

CSPROJ = '''<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net10.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>disable</ImplicitUsings>
    <DebugType>none</DebugType>
    <GenerateDependencyFile>false</GenerateDependencyFile>
    <OutDir>$(MSBuildThisFileDirectory)../</OutDir>
    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>
  </PropertyGroup>
  <ItemGroup>
    <Reference Include="BunnyLoader"><HintPath>{api}</HintPath><Private>false</Private></Reference>
  </ItemGroup>
</Project>
'''

MANIFEST = '''{{
  "uid": "{uid}",
  "id": "{id}",
  "name": "Test: {id}",
  "version": "1.0.0",
  "author": "test",
  "category": "Utilidade",
  "summary": "{summary}",
  "description": "Generated by tools/startup/genentry.py.",
  "updated": "2026-11-23",
  "blVersion": 3,
  "gameVersion": [301720, 301720],
  "dependencies": []
}}
'''


def noise(path, size, rng):
    base = (rng.randrange(256), rng.randrange(256), rng.randrange(256))
    img = Image.new("RGBA", (size, size))
    px = img.load()
    for y in range(size):
        for x in range(size):
            px[x, y] = ((base[0] + x * 7) % 256, (base[1] + y * 5) % 256, (base[2] + x * y) % 256, 255)
    img.save(path)


def item_class(i):
    extra = ""
    if i % 5 == 0:
        extra += "    public override bool? UseItem(Player player) { return true; }\n"
    if i % 7 == 0:
        extra += "    public override void HoldItem(Player player) { player.statDefense += 0; }\n"
    if i % 11 == 0:
        extra += "    public override void UpdateInventory(Player player) { }\n"
    return f"""public sealed class Gen{i:04d} : ModItem
{{
    public override void SetStaticDefaults() {{ Item.ResearchUnlockCount = {i % 100 + 1}; }}
    public override void SetDefaults()
    {{
        Item.width = 20; Item.height = 20; Item.maxStack = 99; Item.value = {i}; Item.rare = {i % 10};
        Item.useStyle = ItemUseStyleID.Swing; Item.useTime = {i % 30 + 10}; Item.useAnimation = {i % 30 + 10};
    }}
{extra}}}
"""


def menu_class(name, count):
    return f"""public sealed class {name}Menu : ModMenu
{{
    static readonly Asset<Texture2D>[] art = new Asset<Texture2D>[{count}];

    public override void Load()
    {{
        for (int i = 0; i < art.Length; i++) art[i] = ModContent.Request<Texture2D>($"{name}/Menu/Art{{i:D3}}");
    }}

    public override void PostDrawLogo(SpriteBatch spriteBatch, Vector2 logoDrawCenter, float logoRotation, float logoScale, Color drawColor)
    {{
        for (int i = 0; i < art.Length; i++)
        {{
            if (!art[i].IsLoaded) continue;
            spriteBatch.Draw(art[i].Value, new Rectangle(8 + i % 16 * 40, 8 + i / 16 * 40, 36, 36), Color.White);
        }}
    }}
}}
"""


def make(index):
    name = f"{args.prefix}{index:02d}"
    root = os.path.join(args.out, name)
    os.makedirs(os.path.join(root, "src"), exist_ok=True)
    rng = random.Random(name)
    uid = str(uuid.uuid5(uuid.NAMESPACE_URL, "bunnyloader-genentry/" + name))
    summary = f"{args.items} items" + (f", menu with {args.menu} textures of {args.menu_size}px" if args.menu else "")
    with io.open(os.path.join(root, "manifest.json"), "w", encoding="utf-8") as f:
        f.write(MANIFEST.format(uid=uid, id=name, summary=summary))
    with io.open(os.path.join(root, "src", f"{name}.csproj"), "w", encoding="utf-8") as f:
        f.write(CSPROJ.format(api=api))
    for i in range(args.items):
        noise(os.path.join(root, f"Gen{i:04d}.png"), 32, rng)
    usings = "using Microsoft.Xna.Framework;\nusing Microsoft.Xna.Framework.Graphics;\nusing ReLogic.Content;\nusing Terraria;\nusing Terraria.ID;\nusing Terraria.ModLoader;\n"
    parts = [usings, f"namespace {name};\npublic sealed class {name}Mod : Mod {{ }}\n"]
    parts += [item_class(i) for i in range(args.items)]
    if args.menu:
        os.makedirs(os.path.join(root, "Menu"), exist_ok=True)
        for i in range(args.menu):
            noise(os.path.join(root, "Menu", f"Art{i:03d}.png"), args.menu_size, rng)
        parts.append(menu_class(name, args.menu))
    with io.open(os.path.join(root, "src", f"{name}.cs"), "w", encoding="utf-8") as f:
        f.write("".join(parts))
    result = subprocess.run(["dotnet", "build", os.path.join(root, "src", f"{name}.csproj"), "-c", "Release", "-nologo", "-v", "q"], capture_output=True, text=True, encoding="utf-8", errors="replace")
    if result.returncode != 0:
        raise SystemExit(f"{name}: build failed\n{result.stdout[-3000:]}")
    print(name, uid, flush=True)


for m in range(args.mods):
    make(m)
